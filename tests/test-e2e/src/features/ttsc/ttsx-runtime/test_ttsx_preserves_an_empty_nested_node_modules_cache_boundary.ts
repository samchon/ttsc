import { FixtureFiles } from "../../../internal/FixtureFiles";
import {
  assert,
  createProject,
  fs,
  path,
  spawn,
  ttscBin,
  ttsxBin,
} from "../../../internal/ttsc/internal/toolchain";

/**
 * Verifies ttsx empty nested install: preserves its cache boundary after use.
 *
 * An intentionally empty `node_modules` is installation evidence. Once ttsx
 * writes `.cache/ttsc` into it, the resolver must remember that it selected the
 * directory instead of switching to a populated ancestor on the next run.
 *
 * 1. Create a nested project with an empty install below a populated install.
 * 2. Assert cache discovery initially selects the nested directory and run ttsx.
 * 3. Assert the same cache root remains selected after its first cache write.
 * @evidence contracts/testing.md#behavioral-verification Queries cache paths before and after a nested runtime and checks the empty nested node_modules remains the selected cache boundary.
 * @evidence contracts/testing.md#independent-expectations The authored nested node_modules path and literal runtime marker establish expected selection independently of cache resolution.
 * @evidence contracts/testing.md#distinguishing-cases An empty nearer install boundary must outrank the populated parent; cache project-directory emptiness is checked after runtime completion.
 * @evidence contracts/testing.md#execution-ownership This second runtime review entry is the named E2E export test_ttsx_preserves_an_empty_nested_node_modules_cache_boundary at this path, selected by tests/test-e2e/evidence.config.json; no direct-source unit equivalence is inferred without comparing its assertions.
 * @evidence contracts/e2e.md#necessary-boundary Two actual cache CLI queries and one ttsx host connect ancestry discovery, cache placement and runtime cleanup.
 * @evidence contracts/e2e.md#shared-execution One project is shared across the three CLI hosts, with no source mutation and no repeated native plugin compilation.
 * @evidence contracts/e2e.md#state-isolation-and-reuse-validity TTSC_CACHE_DIR is cleared for these children; the tracked fixture owns both boundaries and synchronous completion precedes the post-run check.
 * @evidence contracts/e2e.md#preserved-coverage Both cache-path observations, runtime success and empty project-cache assertion remain here; these are three actual host calls.
 */
export function test_ttsx_preserves_an_empty_nested_node_modules_cache_boundary() {
    const root = createProject(FixtureFiles.read("ttsc/ttsx_preserves_an_empty_nested_node_modules_cache_boundary/inputs-1"));
    fs.mkdirSync(path.join(root, "test", "node_modules"));
    const expected = path.join(
      fs.realpathSync(root),
      "test",
      "node_modules",
      ".cache",
      "ttsc",
    );

    assert.equal(cacheRoot(root), expected);
    const result = spawn(
      ttsxBin,
      ["--cwd", root, "--project", "test/tsconfig.json", "test/main.ts"],
      { cwd: root, env: { TTSC_CACHE_DIR: "" } },
    );
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), "empty-install-boundary");
    assert.equal(cacheRoot(root), expected);
    assert.deepEqual(
      fs.readdirSync(path.join(expected, "ttsx", "project")),
      [],
    );
  }

function cacheRoot(root: string): string {
  const result = spawn(
    ttscBin,
    [
      "cache",
      "paths",
      "--json",
      "--cwd",
      root,
      "--project",
      "test/tsconfig.json",
    ],
    { cwd: root, env: { TTSC_CACHE_DIR: "" } },
  );
  assert.equal(result.status, 0, result.stderr);
  return (JSON.parse(result.stdout) as { cacheRoot: string }).cacheRoot;
}
