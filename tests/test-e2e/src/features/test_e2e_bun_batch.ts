import { TestProject, TestUnpluginRuntime } from "@ttsc/testing";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

import { BatchWorkspace } from "../batch/BatchWorkspace";

/**
 * Executes repeated completed builds and a fresh public runtime preload over
 * the same source graph and native producer.
 *
 * @evidence contracts/testing.md#behavioral-verification One Bun child performs two Bun.build passes with the same adapter object and actually loads each distinct delivered CommonJS artifact; both payloads retain the full value/effect oracle. Each pass must add exactly one byte from the owning real probe ApplyProgram, corroborated by independent configured admission epochs. A fresh public bun-register preload child executes the typed source graph, adds its own probe tick and native sequence and returns the same full result.
 * @evidence contracts/testing.md#independent-expectations Literal42/retained and pre-print UTF-16 inputs are independent of Bun's generated bytes. Actual installed runtime emit owns the throwing strip control; this API consumer retains parsed source values.
 * @evidence contracts/testing.md#distinguishing-cases JSX quoting, control characters, JSON aliases and stripped versus retained statements coexist in one source graph.
 * @evidence contracts/testing.md#execution-ownership Selected Bun owns one build child with two real builds and one fresh preload child. Native admission receipts count configured hook invocations, not total Programs, processes or cache hits.
 * @evidence contracts/e2e.md#necessary-boundary Actual Bun resolves the built adapter, runs its native transform callbacks and delivers loadable bundle bytes; callback units cannot certify that host delivery.
 * @evidence contracts/e2e.md#shared-execution Both builds share one child, adapter object and source population. Public preload requires a fresh loader startup and follows actual closure of the build child on the same upfront workspace; it adds one Bun lifetime and no separate install or project. Native producer/preparation totals remain unmeasured.
 * @evidence contracts/e2e.md#state-isolation-and-reuse-validity The child receives an explicit cache path and leaves the input graph unchanged. Nonzero status, signal or spawn error fails; uncertain consumers keep the shared inputs.
 * @evidence contracts/e2e.md#preserved-coverage Restores the original two real-build/one fresh-preload producer tick contrast without the old per-case fixtures. Full typed source/transform values supplement the original literal PLUGIN output. Portable notifyWatchInputs and registration option/name/fallthrough semantics retain their owning units. The named probe tick counts its actual ApplyProgram invocations, not all native Programs or host processes.
 */
export async function test_e2e_bun_batch(): Promise<void> {
  const workspace = await BatchWorkspace.open();
  const receiptOffset = BatchWorkspace.readContextReceipts(workspace).length;
  const tickOffset = fs.existsSync(workspace.programRunLog)
    ? fs.statSync(workspace.programRunLog).size
    : 0;
  const result = TestProject.spawn(
    process.env.TTSC_BUN_BINARY ?? "bun",
    ["bun-entry.mjs"],
    {
      cwd: workspace.root,
      env: {
        TTSC_CACHE_DIR: workspace.cache,
        TTSC_E2E_BUN_RECEIPTS: workspace.contextReceipt,
        TTSC_E2E_BUN_PROGRAM_LOG: workspace.programRunLog,
      },
    },
  );
  assert.equal(result.error, undefined);
  assert.equal(result.signal, null);
  assert.equal(result.status, 0, result.stderr);
  BatchWorkspace.assertResult(
    BatchWorkspace.readPayload(result.stdout),
    workspace.expected,
  );
  const second = result.stdout
    .split(/\r?\n/)
    .filter((line) => line.startsWith("TTSC_BUN_SECOND:"));
  assert.equal(second.length, 1);
  BatchWorkspace.assertResult(
    JSON.parse(second[0].slice("TTSC_BUN_SECOND:".length)),
    workspace.expected,
  );
  const epochLines = result.stdout
    .split(/\r?\n/)
    .filter((line) => line.startsWith("TTSC_BUN_EPOCHS:"));
  assert.equal(epochLines.length, 1);
  const epochs = JSON.parse(
    epochLines[0].slice("TTSC_BUN_EPOCHS:".length),
  ) as number[];
  assert.equal(epochs.length, 3);
  assert.equal(epochs[0], receiptOffset);
  const receipts = BatchWorkspace.readContextReceipts(workspace);
  assert.equal(epochs[2], receipts.length);
  const tickLines = result.stdout
    .split(/\r?\n/)
    .filter((line) => line.startsWith("TTSC_BUN_TICKS:"));
  assert.equal(tickLines.length, 1);
  assert.deepEqual(JSON.parse(tickLines[0].slice("TTSC_BUN_TICKS:".length)), [
    tickOffset,
    tickOffset + 1,
    tickOffset + 2,
  ]);
  assert.equal(fs.statSync(workspace.programRunLog).size, tickOffset + 2);
  for (let pass = 0; pass < 2; pass++) {
    assert.ok(
      Number.isInteger(epochs[pass + 1]) && epochs[pass + 1] > epochs[pass],
    );
    BatchWorkspace.assertContextReceipts(
      receipts.slice(epochs[pass], epochs[pass + 1]),
    );
  }
  if (!(result.pid > 0)) {
    BatchWorkspace.retain("Bun build child returned no owned process identity");
    throw new Error("Bun build child closure unresolved");
  }
  try {
    process.kill(result.pid, 0);
    BatchWorkspace.retain(
      "Bun build child remains live before fresh runtime startup",
    );
    throw new Error("Bun build child closure unresolved");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ESRCH") throw error;
  }
  const runtime = TestProject.spawn(
    process.env.TTSC_BUN_BINARY ?? "bun",
    [
      "--preload",
      path.join(
        path.dirname(TestUnpluginRuntime.libPath("bun", "mjs")),
        "bun-register.mjs",
      ),
      "bun-runtime-entry.mjs",
    ],
    { cwd: workspace.root, env: { TTSC_CACHE_DIR: workspace.cache } },
  );
  assert.equal(runtime.error, undefined);
  assert.equal(runtime.signal, null);
  assert.equal(runtime.status, 0, runtime.stderr);
  BatchWorkspace.assertResult(
    BatchWorkspace.readPayload(runtime.stdout),
    workspace.expected,
  );
  BatchWorkspace.assertContextReceipts(
    BatchWorkspace.readContextReceipts(workspace).slice(epochs[2]),
  );
  assert.equal(
    fs.statSync(workspace.programRunLog).size,
    tickOffset + 3,
    "fresh public runtime preload must acquire its own native probe Program",
  );
}
