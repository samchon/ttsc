import { TestUnpluginProject, TestUnpluginRuntime } from "@ttsc/testing";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

import { cacheEntry } from "../../../../internal/unplugin/internal/transform-external/cacheEntry";
import { emitGraphPlugins } from "../../../../internal/unplugin/internal/transform-graph/emitGraphPlugins";

/**
 * Verifies a `node_modules` declaration under the project root is validated as
 * an external input.
 *
 * The walk skips `node_modules`, so a declaration there lives under the root
 * yet only external validation can see it. That is the everyday shape of a
 * dependency's reinstalled or hand-edited type declarations.
 *
 * 1. Transform an entry whose graph edges to a declaration under `node_modules`.
 * 2. Change that declaration.
 * 3. Transform again and assert the generation was replaced.
 *
 * @evidence contracts/testing.md#behavioral-verification Graph declaration under node_modules changes from first to second and replaces the generation.
 * @evidence contracts/testing.md#independent-expectations The authored graph edge reaches a deliberate excluded-walk declaration; generation inequality observes freshness independently of content-hash calculation.
 * @evidence contracts/testing.md#distinguishing-cases Inside lexical project root but outside project walk still requires external validation.
 * @evidence contracts/testing.md#execution-ownership TestExecutor discovers test_transformttsc_invalidates_project_cache_when_a_node_modules_declaration_changes in native-plugins/transform in the E2E population. Its local callbacks and helper-driven module matrix execute under this named entry; embedded native operations are fixture inputs, not separately selectable test hosts.
 * @evidence contracts/e2e.md#necessary-boundary The built transform API loads the actual consumer descriptor and passes generated options through the native fixture host into returned output and adapter hooks. The fixture validates received paths/options or publishes deliberate effects; direct option derivation cannot prove that process connection.
 * @evidence contracts/e2e.md#shared-execution TestUnpluginProject reuses its immutable Go fixture source and shared content-addressed producer build cache while allocating this consumer independently. Its module requests reuse the supplied transform cache where present; different aliases or producer options legitimately select another transform, without reinstalling the workspace packages.
 * @evidence contracts/e2e.md#state-isolation-and-reuse-validity Consumer, source edits, hook counters and transform cache belong to this case; shared producer inputs remain equivalent or their changed content selects a new build key. TestProject owns its managed temporary roots through runner cleanup. This case does not explicitly reset every retained transform cache; generation disposal and runner termination bound native observer lifetime, rather than a claimed per-case cleanup.
 * @evidence contracts/e2e.md#preserved-coverage Graph declaration under node_modules changes from first to second and replaces the generation. These assertions remain in test_transformttsc_invalidates_project_cache_when_a_node_modules_declaration_changes, with their stated fixture/oracle limits; portable decisions are not claimed covered by an unnamed unit or by a synthetic envelope alone.
 */
export async function test_transformttsc_invalidates_project_cache_when_a_node_modules_declaration_changes(): Promise<void> {
  const { resolveOptions, transformTtsc, createTtscTransformCache } =
    await TestUnpluginRuntime.loadUnpluginApi();
  const root = TestUnpluginProject.createProject({ plugins: [] });
  const declaration = path.join(
    root,
    "node_modules",
    "fixture-types",
    "types.d.ts",
  );
  fs.mkdirSync(path.dirname(declaration), { recursive: true });
  fs.writeFileSync(declaration, "declare const first: string;\n", "utf8");
  const options = resolveOptions({
    plugins: emitGraphPlugins({
      edges: { "src/main.ts": ["node_modules/fixture-types/types.d.ts"] },
    }),
  });
  const cache = createTtscTransformCache();

  const before = await transformTtsc(
    TestUnpluginProject.mainFile(root),
    TestUnpluginProject.mainSource(root),
    options,
    undefined,
    cache,
  );
  assert.ok(before);
  const generation = cacheEntry(cache);

  fs.writeFileSync(declaration, "declare const second: string;\n", "utf8");
  const after = await transformTtsc(
    TestUnpluginProject.mainFile(root),
    TestUnpluginProject.mainSource(root),
    options,
    undefined,
    cache,
  );
  assert.ok(after);
  assert.notStrictEqual(cacheEntry(cache), generation);
}
