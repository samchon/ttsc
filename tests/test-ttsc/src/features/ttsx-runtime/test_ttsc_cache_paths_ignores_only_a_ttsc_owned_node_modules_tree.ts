import { TestProject } from "../../../../utils/src/TestProject";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { resolveSourceBuildCachePaths } from "../../../../../packages/ttsc/src/plugin/internal/source/resolveSourceBuildCachePaths";

/**
 * Verifies cache paths: ignores only a ttsc-owned node_modules tree.
 *
 * A previous ttsx release can leave `.cache/ttsc` under a nested tsconfig. The
 * resolver must recover from that owned state without ignoring a real nested
 * installation that also happens to contain the cache.
 *
 * 1. Seed a root install and a legacy nested ttsx cache as the only child.
 * 2. Assert cache discovery ignores the owned tree and selects the root.
 * 3. Add one installed package and assert the nested boundary now wins.
 * 4. Add a workspace marker and assert its root overrides that installation.
 *
 * @evidence contracts/testing.md#behavioral-verification The actual source-build cache resolver interprets the fixture's installation and owned-cache boundaries and returns the asserted root without invoking the CLI.
 * @evidence contracts/testing.md#independent-expectations Expected native paths follow explicit fixture ownership: an installed dependency and workspace marker are authoritative, while a legacy ttsx-only payload is not an installation.
 * @evidence contracts/testing.md#distinguishing-cases The same nested legacy cache yields the outer installation; adding a real nested dependency changes the root, and adding a workspace marker restores workspace ownership.
 * @evidence contracts/testing.md#execution-ownership Unit test discovered once under src/features/ttsx-runtime; it calls resolveSourceBuildCachePaths with an empty env over directories written to a TestProject.createProject tree, and starts no CLI, compiler or process.
 */
export function test_ttsc_cache_paths_ignores_only_a_ttsc_owned_node_modules_tree() {
    const root = TestProject.createProject({
      "package.json": JSON.stringify({ name: "legacy-cache-root" }),
      "test/main.ts": `export const value = 1;\n`,
      "test/tsconfig.json": JSON.stringify({
        compilerOptions: { outDir: "../dist", rootDir: "." },
        include: ["main.ts"],
      }),
    });
    const physicalRoot = fs.realpathSync.native(root);
    fs.mkdirSync(path.join(root, "node_modules"));
    fs.mkdirSync(
      path.join(
        root,
        "test",
        "node_modules",
        ".cache",
        "ttsc",
        "ttsx",
        "project",
      ),
      { recursive: true },
    );

    assert.equal(
      cacheRoot(root),
      path.join(physicalRoot, "node_modules", ".cache", "ttsc"),
    );

    fs.mkdirSync(path.join(root, "test", "node_modules", "dependency"));
    assert.equal(
      cacheRoot(root),
      path.join(physicalRoot, "test", "node_modules", ".cache", "ttsc"),
    );

    fs.writeFileSync(
      path.join(root, "pnpm-workspace.yaml"),
      "packages:\n  - test\n",
    );
    assert.equal(
      cacheRoot(root),
      path.join(physicalRoot, "node_modules", ".cache", "ttsc"),
    );
}

function cacheRoot(root: string): string {
 return resolveSourceBuildCachePaths(path.join(fs.realpathSync.native(root), "test"), undefined, {}).root;
}
