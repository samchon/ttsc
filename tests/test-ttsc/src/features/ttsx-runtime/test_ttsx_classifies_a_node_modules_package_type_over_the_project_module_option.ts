import { TestProject } from "@ttsc/testing";
import assert from "node:assert/strict";

/**
 * Verifies a source-shipping `node_modules` package's own `"type"` decides its
 * format, even when the compiling project asks for a different module kind.
 *
 * Tsgo reads a file's `packageJsonType` only for paths under `node_modules`,
 * and `getImpliedNodeFormatForEmitWorker` consults that field for _every_
 * module kind, not just the `node*` family. So a dependency declaring `"type":
 * "commonjs"` is emitted as CommonJS while the consuming project is on
 * `esnext`. A classifier that answered from the project's `module` alone would
 * hand Node an ES-module label for a CommonJS body and fail with `exports is
 * not defined in ES module scope`.
 *
 * 1. Publish a raw-`.ts` dependency under `node_modules` whose manifest declares
 *    `"type": "commonjs"` and whose own tsconfig says `module: esnext`.
 * 2. Import it from an `esnext` entry project and run ttsx.
 * 3. Assert the run succeeds and the dependency's value arrived.
 */
export const test_ttsx_classifies_a_node_modules_package_type_over_the_project_module_option =
  () => {
    const root = TestProject.createProject({
      "package.json": JSON.stringify({
        name: "consumer",
        version: "1.0.0",
        type: "module",
      }),
      "tsconfig.json": JSON.stringify({
        compilerOptions: {
          target: "ES2022",
          module: "esnext",
          moduleResolution: "bundler",
          strict: true,
          outDir: "lib",
          rootDir: "src",
        },
        include: ["src"],
      }),
      "src/main.ts": `import { value } from "dep";\nconsole.log(value);\n`,
      "node_modules/dep/package.json": JSON.stringify({
        name: "dep",
        version: "1.0.0",
        type: "commonjs",
        exports: { ".": "./index.ts" },
      }),
      "node_modules/dep/tsconfig.json": JSON.stringify({
        compilerOptions: {
          target: "ES2022",
          module: "esnext",
          moduleResolution: "bundler",
          strict: true,
        },
        include: ["."],
      }),
      "node_modules/dep/index.ts": `export const value: string = "cjs-dependency";\n`,
    });

    const result = TestProject.spawn(
      TestProject.TTSX_BIN,
      ["--cwd", root, "src/main.ts"],
      { cwd: root },
    );
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), "cjs-dependency");
  };
