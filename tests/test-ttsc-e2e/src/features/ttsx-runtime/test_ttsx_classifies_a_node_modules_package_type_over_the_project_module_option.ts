import { TestProject } from "@ttsc/testing";
import assert from "node:assert/strict";

/**
 * Verifies a source-shipping `node_modules` package's own `"type"` decides its
 * format, even when the compiling project asks for a different module kind.
 *
 * `getImpliedNodeFormatForEmitWorker` consults a file's `packageJsonType` for
 * _every_ module kind, not just the `node*` family, and `node_modules` is where
 * that field can be set for a kind this override changes. So a dependency
 * declaring `"type": "commonjs"` is emitted as CommonJS while the consuming
 * project is on `esnext`. A classifier that answered from the project's
 * `module` alone would hand Node an ES-module label for a CommonJS body and
 * fail with `exports is not defined in ES module scope`.
 *
 * `src/Node_Modules` is the negative twin. Upstream's test is a case-sensitive
 * substring search, so a differently-cased directory is not a package store to
 * it and its manifest must not out-vote the project. A classifier that folded
 * case would call that ESM emit CommonJS and Node would reject its `export`.
 *
 * 1. Publish a raw-`.ts` dependency under `node_modules` whose manifest declares
 *    `"type": "commonjs"` and whose own tsconfig says `module: esnext`, plus a
 *    same-shaped package under a miscased `Node_Modules`.
 * 2. Import both from an `esnext` entry project and run ttsx.
 * 3. Assert the run succeeds and both values arrived.
 *
 * @evidence contracts/testing.md#behavioral-verification Actual ttsx imports a CommonJS raw package and a miscased non-package-store source under an esnext program; zero status and exact cjs-dependency|esm-by-project output detect either format mismatch.
 * @evidence contracts/testing.md#independent-expectations Upstream per-file emit precedence lets literal node_modules package type override esnext but leaves differently cased Node_Modules under the project module; authored literal exports independently establish both results.
 * @evidence contracts/testing.md#distinguishing-cases The CommonJS dependency and negative miscased sibling differ only in package-store ownership; the direct RuntimeModuleFormat source unit owns the full manifest, extension and option matrix.
 * @evidence contracts/testing.md#execution-ownership One named feature entry invokes the actual launcher, native compiler and Node loader for both opposite scopes, with authored modules as fixture inputs.
 * @evidence contracts/e2e.md#necessary-boundary Actual compiler per-file emit and host format labels must agree across the dependency store boundary; direct classification cannot prove the compiler produced the body that the label serves.
 * @evidence contracts/e2e.md#shared-execution Both opposite scopes share one immutable root program and one Node session; the dependency-owned esnext profile requires its own preparation and the consumer still repeats a standalone root preparation outside the central ESM batch.
 * @evidence contracts/e2e.md#state-isolation-and-reuse-validity Distinct dependency and project paths prevent Node cache aliasing; synchronous spawn ends before TestProject releases the fixture, and no changing-source or cold-cache transition is asserted.
 * @evidence contracts/e2e.md#preserved-coverage Original successful status and both exact values remain together; no filesystem case folding replaces the compiler-defined literal-directory distinction.
 */
export function test_ttsx_classifies_a_node_modules_package_type_over_the_project_module_option() {
    const root = TestProject.createProject({
      "package.json": JSON.stringify({
        name: "consumer",
        version: "1.0.0",
        type: "module",
      }),
      "tsconfig.json": JSON.stringify({
        compilerOptions: {
          target: "ES2022",
          module: "esnext",
          moduleResolution: "bundler",
          strict: true,
          outDir: "lib",
          rootDir: "src",
        },
        include: ["src"],
      }),
      "src/main.ts": [
        `import { value } from "dep";`,
        `import { plain } from "./Node_Modules/plain/index";`,
        `console.log(value + "|" + plain);`,
        "",
      ].join("\n"),
      // Not a package store to Node or to tsgo, whatever the volume's case
      // folding says. Its manifest must lose to the project's own `module`.
      "src/Node_Modules/plain/package.json": JSON.stringify({
        name: "plain",
        version: "1.0.0",
        type: "commonjs",
      }),
      "src/Node_Modules/plain/index.ts": `export const plain: string = "esm-by-project";\n`,
      "node_modules/dep/package.json": JSON.stringify({
        name: "dep",
        version: "1.0.0",
        type: "commonjs",
        exports: { ".": "./index.ts" },
      }),
      "node_modules/dep/tsconfig.json": JSON.stringify({
        compilerOptions: {
          target: "ES2022",
          module: "esnext",
          moduleResolution: "bundler",
          strict: true,
        },
        include: ["."],
      }),
      "node_modules/dep/index.ts": `export const value: string = "cjs-dependency";\n`,
    });

    const result = TestProject.spawn(
      TestProject.TTSX_BIN,
      ["--cwd", root, "src/main.ts"],
      { cwd: root },
    );
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), "cjs-dependency|esm-by-project");
  }
