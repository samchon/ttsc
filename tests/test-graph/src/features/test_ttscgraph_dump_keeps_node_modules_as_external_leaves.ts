import { findEdge, findNode } from "../internal/graphDump";
import { getIdentityDump } from "../internal/identityBoundary";
import { assert } from "../internal/ttsgraph";

/**
 * Verifies graph dump reaches node_modules declarations only as external
 * leaves.
 *
 * Dependency type definitions matter as endpoints: a local API can extend an
 * imported class, call an imported function, or expose an imported type. The
 * graph should keep those direct targets so an agent sees the dependency
 * boundary, but it must not index every declaration in node_modules because
 * that would turn the project graph into a dependency graph and bury authored
 * code.
 *
 * 1. Materialize a package with a node_modules `.d.ts` dependency.
 * 2. Reference three exported dependency symbols from local source.
 * 3. Assert those targets are external leaves and an unreferenced dependency
 *    declaration is absent.
 *
 * @evidence contracts/testing.md#behavioral-verification Real dump returns referenced external function/interface/class leaves and local declarations, with calls/type_ref/extends edges, while omitting an unreferenced dependency detail.
 * @evidence contracts/testing.md#independent-expectations Authored imports and uses independently name the required nodes and edge kinds; the unused declaration is a literal negative control against dumping dependency internals.
 * @evidence contracts/testing.md#distinguishing-cases Referenced external leaves contrast local definitions and an unreferenced external detail; external flags distinguish dependency boundaries from workspace facts.
 * @evidence contracts/testing.md#execution-ownership The features export test_ttscgraph_dump_keeps_node_modules_as_external_leaves runs the actual native dump producer on its fixture project; it remains in the E2E runner/Evidence population, with the per-case assertions above rather than source-unit execution.
 * @evidence contracts/e2e.md#necessary-boundary Native module resolution and checker edge production must preserve external leaves in actual dump JSON; synthetic nodes cannot test dependency traversal pruning.
 * @evidence contracts/e2e.md#shared-execution Thirty-one native graph entries share one project: twenty-eight borrow one initialized MCP/native session, and four immutable producer assertions borrow one cached public CLI dump (checker uses both). Raw-only selections prepare no MCP. MCP ranking, exact tag queries and recursive/terminal/dispatch-threshold contrasts select closed source universes; edits and config restoration advance actual generations without fresh clients.
 * @evidence contracts/e2e.md#state-isolation-and-reuse-validity Disjoint files, contracts, citations, aliases, external declarations and a physical workspace link preserve distinctions. MCP/tag scopes and invalid-config recovery restore config bytes finally; tour/hub variants overwrite only their own source and scope include to that file, retaining exact population/order/topology before each native request. Cached CLI facts serve unchanged assertions, and suite finally joins its client after complete collection.
 * @evidence contracts/e2e.md#preserved-coverage All node/flag checks, calls/type_ref/extends edges and unused-detail absence remain in this producer boundary case.
 */
export const test_ttscgraph_dump_keeps_node_modules_as_external_leaves = async () => {
  const dump = await getIdentityDump();
  const run = findNode(dump, {
    file: "src/external-main.ts",
    name: "run",
    kind: "function",
  });
  const localService = findNode(dump, {
    file: "src/external-main.ts",
    name: "LocalService",
    kind: "class",
  });
  const externalHelper = findNode(dump, {
    file: "node_modules/external-leaves/index.d.ts",
    name: "externalHelper",
    kind: "function",
  });
  const externalPayload = findNode(dump, {
    file: "node_modules/external-leaves/index.d.ts",
    name: "ExternalPayload",
    kind: "interface",
  });
  const externalService = findNode(dump, {
    file: "node_modules/external-leaves/index.d.ts",
    name: "ExternalService",
    kind: "class",
  });

  assert.ok(run, "local function is present");
  assert.ok(localService, "local class is present");
  assert.ok(externalHelper, "referenced external function is kept");
  assert.ok(externalPayload, "referenced external interface is kept");
  assert.ok(externalService, "referenced external class is kept");
  assert.equal(externalHelper.external, true);
  assert.equal(externalPayload.external, true);
  assert.equal(externalService.external, true);
  assert.ok(
    findEdge(dump, run, externalHelper, "calls"),
    "local call reaches the external function leaf",
  );
  assert.ok(
    findEdge(dump, run, externalPayload, "type_ref"),
    "local type annotation reaches the external type leaf",
  );
  assert.ok(
    findEdge(dump, localService, externalService, "extends"),
    "local heritage reaches the external class leaf",
  );
  assert.equal(
    dump.nodes.some((node) => node.name === "UnusedDependencyDetail"),
    false,
    "unreferenced node_modules declarations are not indexed",
  );
};
