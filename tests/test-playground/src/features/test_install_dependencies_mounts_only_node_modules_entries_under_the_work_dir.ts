import { createMemFS } from "@ttsc/wasm";
import assert from "node:assert/strict";

import { installDependenciesIntoMemFS } from "../../../../packages/playground/src/compiler/installDependenciesIntoMemFS";
import { normalizeNodeModulePath } from "../../../../packages/playground/src/compiler/normalizeNodeModulePath";

/**
 * Verifies the dependency mount writes each `node_modules` entry under the work
 * directory, skips every other path, and counts only what it wrote.
 *
 * The installer on the UI side submits package files by virtual path. The mount
 * accepts only paths below `node_modules` (in any slash spelling) and refuses
 * any that climb out of it, because a path written outside would replace the
 * project's own source or escape the virtual project root.
 *
 * 1. Submit relative, leading-slash and backslash `node_modules` paths together
 *    with source, parent-climbing, bare-directory, look-alike-directory and
 *    wrong-case paths.
 * 2. Read the work directory and the paths that must stay untouched back from a
 *    real MemFS and compare the returned count and package list.
 * 3. Repeat under a nested work directory and normalize the path spellings
 *    directly.
 *
 * @evidence contracts/testing.md#behavioral-verification installDependenciesIntoMemFS writes node_modules entries under the work directory, returns the submitted package list and the number of files written, and leaves everything else absent from the real MemFS. Reading the bytes back and probing the refused locations reject both a skipped valid entry and a write outside the root.
 * @evidence contracts/testing.md#independent-expectations Node module resolution reads packages from a node_modules directory and a path segment `..` climbs out of it, so those paths must not be written; the expected bytes A, B, C and the literal count 3 are authored with the input. The expected normalized spellings are written by hand.
 * @evidence contracts/testing.md#distinguishing-cases Three accepted spellings contrast with a source path, two parent-climbing paths (leading and embedded), a bare node_modules name, a look-alike directory name and a wrong-case name, and the nested work directory contrasts with the default; none of the refused paths may appear anywhere in the filesystem.
 * @evidence contracts/testing.md#execution-ownership This entry calls the actual mount and path-normalizing functions against createMemFS in the unit process; no browser, network or installed package is used. The registry download that produces these file maps is owned by the test_npm_registry_* entries.
 */
export function test_install_dependencies_mounts_only_node_modules_entries_under_the_work_dir(): void {
  const packages = [{ name: "uuid", version: "9.0.0" }] as never;
  const files = {
    "node_modules/uuid/index.js": "A",
    "/node_modules/b/i.js": "B",
    "node_modules\\win\\x.js": "C",
    "src/evil.js": "X",
    "node_modules/../etc/passwd": "Y",
    "../node_modules/z.js": "Z",
    "node_modules/a/../../out.js": "W",
    node_modules: "V",
    "other_node_modules/x.js": "O",
    "NODE_MODULES/x.js": "U",
  };

  const host = createMemFS();
  const result = installDependenciesIntoMemFS(host, "/work", {
    files,
    packages,
  });
  assert.equal(result.fileCount, 3);
  assert.equal(result.installed, packages);
  assert.deepEqual(
    [
      host.readFileText("/work/node_modules/uuid/index.js"),
      host.readFileText("/work/node_modules/b/i.js"),
      host.readFileText("/work/node_modules/win/x.js"),
    ],
    ["A", "B", "C"],
  );
  for (const refused of [
    "/work/src/evil.js",
    "/work/etc/passwd",
    "/etc/passwd",
    "/work/out.js",
    "/out.js",
    "/work/z.js",
    "/z.js",
    "/work/other_node_modules",
    "/work/NODE_MODULES",
    "/work/node_modules/a",
    "/node_modules",
  ])
    assert.equal(host.exists(refused), false, refused);

  const nested = createMemFS();
  const nestedResult = installDependenciesIntoMemFS(nested, "/a/b", {
    files: { "node_modules/p/i.js": "N", "src/evil.js": "X" },
    packages: [],
  });
  assert.equal(nestedResult.fileCount, 1);
  assert.equal(nested.readFileText("/a/b/node_modules/p/i.js"), "N");
  assert.equal(nested.exists("/a/b/src/evil.js"), false);
  assert.equal(
    installDependenciesIntoMemFS(createMemFS(), "/work", {
      files: {},
      packages: [],
    }).fileCount,
    0,
  );

  assert.equal(normalizeNodeModulePath("node_modules/x"), "node_modules/x");
  assert.equal(normalizeNodeModulePath("///node_modules/x"), "node_modules/x");
  assert.equal(normalizeNodeModulePath("\\node_modules\\x"), "node_modules/x");
  assert.equal(normalizeNodeModulePath("node_modules/x/.."), null);
  assert.equal(normalizeNodeModulePath("node_modules"), null);
  assert.equal(normalizeNodeModulePath(""), null);
}
