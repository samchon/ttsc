import assert from "node:assert/strict";
import path from "node:path";

import { TestProject } from "../../../../utils/src/TestProject";
import { runTurbopackLoader } from "../internal/adapter-turbopack/runTurbopackLoader";

/**
 * Verifies the Turbopack loader passes declaration files and `node_modules`
 * sources through byte for byte.
 *
 * A broad `*.ts` rule glob routes everything with the extension through the
 * loader, so the loader must mirror the unplugin adapters' `transformInclude`
 * guard itself instead of relying on the rule to exclude them.
 *
 * 1. Run the loader on an ambient `.d.ts` file inside a project.
 * 2. Run it on a TypeScript source under `node_modules`.
 * 3. Assert both return their source unchanged.
 *
 * @evidence contracts/testing.md#behavioral-verification
 *   Calls the authored Turbopack loader for an ambient declaration and a
 *   vendored TypeScript module, asserting callback source bytes are unchanged.
 * @evidence contracts/testing.md#independent-expectations
 *   Whole-project transforms exclude declarations and node_modules sources.
 *   Deliberately supplied declaration and module strings are independent oracles.
 * @evidence contracts/testing.md#distinguishing-cases
 *   A declaration inside source and an ordinary TypeScript extension inside
 *   node_modules independently exercise the two exclusions. The companion unit
 *   owns JavaScript and virtual inputs; packed Turbopack owns real source delivery.
 * @evidence contracts/testing.md#execution-ownership
 *   test_turbopack_loader_passes_through_declarations_and_node_modules calls runTurbopackLoader, which invokes authored loader completion on declaration/vendor literals; both exact results belong to this entry, with no installed package or producer.
 */
export async function test_turbopack_loader_passes_through_declarations_and_node_modules(): Promise<void> {
  const root = TestProject.tmpdir("adapter-source-unit-");
  const declaration = "declare const ambient: number;\n";
  const declarationOut = await runTurbopackLoader({
    resourcePath: path.join(root, "src", "ambient.d.ts"),
    source: declaration,
  });
  assert.equal(declarationOut, declaration);

  const vendored = 'export const value: string = goUpper("plugin");\n';
  const vendoredOut = await runTurbopackLoader({
    resourcePath: path.join(root, "node_modules", "pkg", "main.ts"),
    source: vendored,
  });
  assert.equal(vendoredOut, vendored);
}
