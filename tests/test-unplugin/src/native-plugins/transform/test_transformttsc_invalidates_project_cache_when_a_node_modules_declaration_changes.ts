import { TestUnpluginProject, TestUnpluginRuntime } from "@ttsc/testing";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

import { cacheEntry } from "../../internal/transform-external/cacheEntry";
import { emitGraphPlugins } from "../../internal/transform-graph/emitGraphPlugins";

/**
 * Verifies a `node_modules` declaration under the project root is validated as
 * an external input.
 *
 * The walk skips `node_modules`, so a declaration there lives under the root
 * yet only external validation can see it. That is the everyday shape of a
 * dependency's reinstalled or hand-edited type declarations.
 *
 * 1. Transform an entry whose graph edges to a declaration under `node_modules`.
 * 2. Change that declaration.
 * 3. Transform again and assert the generation was replaced.
 */
export async function test_transformttsc_invalidates_project_cache_when_a_node_modules_declaration_changes(): Promise<void> {
  const { resolveOptions, transformTtsc, createTtscTransformCache } =
    await TestUnpluginRuntime.loadUnpluginApi();
  const root = TestUnpluginProject.createProject({ plugins: [] });
  const declaration = path.join(
    root,
    "node_modules",
    "fixture-types",
    "types.d.ts",
  );
  fs.mkdirSync(path.dirname(declaration), { recursive: true });
  fs.writeFileSync(declaration, "declare const first: string;\n", "utf8");
  const options = resolveOptions({
    plugins: emitGraphPlugins({
      edges: { "src/main.ts": ["node_modules/fixture-types/types.d.ts"] },
    }),
  });
  const cache = createTtscTransformCache();

  const before = await transformTtsc(
    TestUnpluginProject.mainFile(root),
    TestUnpluginProject.mainSource(root),
    options,
    undefined,
    cache,
  );
  assert.ok(before);
  const generation = cacheEntry(cache);

  fs.writeFileSync(declaration, "declare const second: string;\n", "utf8");
  const after = await transformTtsc(
    TestUnpluginProject.mainFile(root),
    TestUnpluginProject.mainSource(root),
    options,
    undefined,
    cache,
  );
  assert.ok(after);
  assert.notStrictEqual(cacheEntry(cache), generation);
}
