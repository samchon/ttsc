const assert = require("node:assert/strict");
const cp = require("node:child_process");
const crypto = require("node:crypto");
const fs = require("node:fs");
const { createRequire } = require("node:module");
const os = require("node:os");
const path = require("node:path");

const repository = path.resolve(__dirname, "../..");

/**
 * Verifies the shipped compiler and native platform tools in a bare consumer.
 *
 * A structured onConsumerCreated callback receives a fresh allocation before
 * preparation. With keep:true it owns that root even if preparation throws;
 * a rejecting callback leaves cleanup with this constructor. Default calls
 * preserve the ordinary keep/reuse lifecycle.
 *
 * 1. Prepare a new packed consumer or validate the explicitly reused owner.
 * 2. Execute installed Node and native launchers and bundled Go version probes.
 * 3. Compile and run the authored message with emit and the TypeScript runtime.
 * 4. Release the consumer unless its confirmed owner requested retention.
 *
 * @evidence contracts/testing.md#behavioral-verification
 *   Executes installed ttsc/ttsx versions, native server/graph versions, bundled
 *   Go, compiler emit, emitted JavaScript and TypeScript runtime. Literal version
 *   prefixes and installed-cli-ok distinguish broken packaging or launch wiring.
 * @evidence contracts/testing.md#independent-expectations
 *   The fixture's authored message determines stdout independently of the
 *   compiler. CLI version prefixes and native TypeScript's major version are
 *   supported package contracts rather than results generated by a launcher;
 *   borrowed archives additionally compare their exact manifests and maintained
 *   SDK Go source bytes against the current checkout before installation.
 * @evidence contracts/testing.md#distinguishing-cases
 *   Checks Node launchers, directly executable platform binaries, bundled Go,
 *   emit and runtime separately. The consumer declares no transform plugins;
 *   packed installation's separate plugin batch owns plugin discovery and errors.
 * @evidence contracts/testing.md#execution-ownership
 *   This named E2E entry is the executable CLI smoke command. Fresh default
 *   mode owns installation; shared mode owns a distinct consumer over the packed
 *   install; reuse mode runs the same actual assertions on another Node version.
 *   Structured archiveDirectory input borrows already packed immutable bytes
 *   into a newly installed consumer without repacking or editing their owner.
 *   onConsumerCreated synchronously transfers the allocated root before marker,
 *   archive or install work, including when later preparation fails.
 * @evidence contracts/e2e.md#necessary-boundary
 *   Actual packed artifacts must locate their native peer and SDK and run from
 *   a consumer without checkout overrides. Direct resolver units cannot prove
 *   the native binaries launch or the installed runtime executes emitted code.
 * @evidence contracts/e2e.md#shared-execution
 *   E2E's --consumer shares the adapter batch's tarball install, linking only
 *   compiler, platform and native TypeScript into a fresh bare consumer. --keep
 *   and --reuse share that fixture across Node probes. Default mode preserves
 *   the independent installation required by the sole install OS matrix;
 *   archiveDirectory retains that real installation while sharing exact tarballs.
 * @evidence contracts/e2e.md#state-isolation-and-reuse-validity
 *   The minimal direct manifest prevents automatic adapter plugin discovery.
 *   Native TypeScript is remapped from the store's alias while Next retains its
 *   legacy peer. Each Node command clears binary, SDK and cache overrides; fresh
 *   invocation directories are removed in finally unless kept for later probes.
 * @evidence contracts/e2e.md#preserved-coverage
 *   Both preparation modes retain all original version, SDK, emit and runtime
 *   assertions. Shared preparation additionally verifies installed package names,
 *   native peer major and real tarball receipts; reuse verifies the owner marker
 *   before running the same assertions under the selected Node executable.
 */
function test_installed_cli_smoke(options = {}) {
const reuse = process.argv.includes("--reuse");
const keep = options.keep ?? process.argv.includes("--keep");
const consumer = process.argv.find((argument) => argument.startsWith("--consumer="))?.slice("--consumer=".length);
assert(!(reuse && consumer), "--reuse and --consumer are independent preparation modes");
assert(!options.archiveDirectory || (!reuse && !consumer), "Borrowed archives require a newly installed consumer");
const workspace = reuse
  ? process.env.TTSC_INSTALLED_SMOKE_ROOT
  : fs.mkdtempSync(path.join(os.tmpdir(), "ttsc-cli-smoke-"));
assert(workspace, "--reuse requires TTSC_INSTALLED_SMOKE_ROOT");
const marker = path.join(workspace, ".ttsc-cli-smoke");
let consumerTransferred = false;

try {
  if (options.onConsumerCreated) {
    assert(!reuse, "A reused consumer cannot transfer new allocation ownership");
    options.onConsumerCreated(workspace);
    consumerTransferred = true;
  }
  console.log(`Installed CLI consumer: ${workspace}`);
  if (reuse) assert.equal(fs.readFileSync(marker, "utf8"), repository);
  else {
    fs.writeFileSync(marker, repository);
    const platform = `ttsc-${process.platform}-${process.arch}`;
    if (options.archiveDirectory) borrowArchives(options.archiveDirectory, platform);
    else if (!consumer)
      for (const name of ["ttsc", platform])
        runPnpm(["pack", "--out", path.join(workspace, `${name}.tgz`)], path.join(repository, "packages", name));
    fs.writeFileSync(path.join(workspace, "package.json"), JSON.stringify({
      private: true,
      dependencies: {
        ttsc: "file:./ttsc.tgz",
        [`@ttsc/${process.platform}-${process.arch}`]: `file:./${platform}.tgz`,
        typescript: "7.0.2",
      },
    }));
    if (consumer) linkPackedConsumer(consumer);
    else runPnpm(["install", "--ignore-scripts", "--no-frozen-lockfile"], workspace);
    fs.mkdirSync(path.join(workspace, "src"));
    fs.writeFileSync(path.join(workspace, "tsconfig.json"), JSON.stringify({
      compilerOptions: { target: "ES2022", module: "commonjs", strict: true, rootDir: "src", outDir: "dist" },
      include: ["src"],
    }));
    fs.writeFileSync(path.join(workspace, "src", "message.ts"), 'export const message: string = "installed-cli-ok";\n');
    fs.writeFileSync(path.join(workspace, "src", "main.ts"), 'import { message } from "./message";\nconsole.log(message);\n');
  }
  const requireInstalled = createRequire(path.join(workspace, "package.json"));
  const manifestPath = requireInstalled.resolve("ttsc/package.json");
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  const typescriptManifest = JSON.parse(fs.readFileSync(requireInstalled.resolve("typescript/package.json"), "utf8"));
  assert.equal(typescriptManifest.name, "typescript");
  assert.match(typescriptManifest.version, /^7\./, "installed smoke resolves native TypeScript, not Next's legacy peer");
  const launcher = (name) => path.join(path.dirname(manifestPath), manifest.bin[name]);
  const platform = path.dirname(
    requireInstalled.resolve(`@ttsc/${process.platform}-${process.arch}/package.json`),
  );
  const native = (name) =>
    path.join(platform, "bin", `${name}${process.platform === "win32" ? ".exe" : ""}`);
  assert.match(runNode([launcher("ttsc"), "--version"]), /^ttsc /m);
  const runtimeVersion = runNode([launcher("ttsx"), "--version"]);
  assert.match(runtimeVersion, /^ttsx /m);
  assert.match(runtimeVersion, /\(Version [^)]+\)/);
  const runtimeHelp = runNode([launcher("ttsx"), "--help"]);
  assert.match(runtimeHelp, /TypeScript runner provided by ttsc\./);
  assert.match(runtimeHelp, /ttsx \[options\] <entry> \[argv\.\.\.\]/);
  assert.match(
    runInstalledBinary(native("ttscserver"), ["--version"]),
    /^ttscserver /m,
  );
  assert.match(
    runInstalledBinary(native("ttscgraph"), ["--version"]),
    /^ttscgraph /m,
  );
  const bundledGo = path.join(
    platform,
    "bin",
    "go",
    "bin",
    process.platform === "win32" ? "go.exe" : "go",
  );
  assert.match(runInstalledBinary(bundledGo, ["version"]), /^go version go/m);
  runNode([launcher("ttsc"), "--emit"]);
  assert.equal(runNode([path.join(workspace, "dist", "main.js")]).trim(), "installed-cli-ok");
  assert.equal(runNode([launcher("ttsx"), "src/main.ts"]).trim(), "installed-cli-ok");
  if (keep && process.env.GITHUB_ENV)
    fs.appendFileSync(process.env.GITHUB_ENV, `TTSC_INSTALLED_SMOKE_ROOT=${workspace}\n`);
  console.log(`Installed CLI smoke passed on ${process.platform}/${process.arch}, Node ${process.versions.node}`);
  return workspace;
} finally {
  // Fresh scratch directories are owned by this invocation. A reused consumer
  // stays for the next Node-version probe in the same job.
  if (!reuse && (!keep || (options.onConsumerCreated && !consumerTransferred)))
    fs.rmSync(workspace, { recursive: true, force: true });
}

function runNode(args) {
  const environment = { ...process.env };
  // Exercise the installed package's resolution, never a checkout override.
  for (const key of ["TTSC_BINARY", "TTSC_TSGO_BINARY", "TTSC_GO_BINARY", "TTSC_CACHE_DIR", "TTSC_GO_CACHE_DIR", "TTSC_TEST_CACHE_DIR", "NODE_OPTIONS", "TTSX_RUNTIME_MANIFEST"])
    delete environment[key];
  const result = cp.spawnSync(process.execPath, args, { cwd: workspace, env: environment, encoding: "utf8", windowsHide: true, timeout: 120_000 });
  if (result.error) throw result.error;
  assert.equal(result.status, 0, result.stderr || result.stdout);
  return result.stdout;
}

// A separate bare consumer declares only the compiler, its native platform and
// TypeScript. Linking the packed store shares installation without inheriting
// the adapter consumer's automatic plugin dependencies or mutable source tree.
function linkPackedConsumer(consumerRoot) {
  const modules = fs.realpathSync(path.join(path.resolve(consumerRoot), "node_modules"));
  const installed = JSON.parse(fs.readFileSync(path.join(path.dirname(modules), "package.json"), "utf8"));
  const platform = `@ttsc/${process.platform}-${process.arch}`;
  const dependencies = {};
  for (const [name, sourceName] of [["ttsc", "ttsc"], [platform, platform], ["typescript", "typescript-native"]]) {
    const source = path.join(modules, sourceName);
    const manifest = JSON.parse(fs.readFileSync(path.join(source, "package.json"), "utf8"));
    assert.equal(manifest.name, name);
    if (name === "typescript") assert.match(manifest.version, /^7\./);
    else {
      const archive = installed.dependencies?.[name];
      assert.match(archive ?? "", /^file:.*\.tgz$/, `${name} must come from the packed consumer's tarball install`);
      assert(fs.statSync(path.resolve(path.dirname(modules), archive.slice(5))).isFile());
    }
    const destination = path.join(workspace, "node_modules", name);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.symlinkSync(source, destination, process.platform === "win32" ? "junction" : "dir");
    dependencies[name] = manifest.version;
  }
  fs.writeFileSync(path.join(workspace, "package.json"), JSON.stringify({ private: true, dependencies }));
}

// Borrowed inputs stay read-only. Extraction and copying only target this
// invocation's direct temporary consumer; no package-manager store is adopted.
function borrowArchives(directory, platform) {
  const source = fs.realpathSync.native(path.resolve(directory));
  const verification = path.join(workspace, "archive-receipt");
  fs.mkdirSync(verification);
  for (const name of ["ttsc", platform]) {
    const input = path.join(source, `${name}.tgz`);
    assert(fs.lstatSync(input).isFile(), `Borrowed archive must be an ordinary file: ${input}`);
    const receipt = fileDigest(input);
    const output = path.join(workspace, `${name}.tgz`);
    fs.copyFileSync(input, output, fs.constants.COPYFILE_EXCL);
    assert.equal(fileDigest(output), receipt);
    const manifestResult = cp.spawnSync("tar", ["-xOf", output, "package/package.json"], {
      encoding: "utf8", windowsHide: true, timeout: 120_000, maxBuffer: 1024 * 1024,
    });
    if (manifestResult.error) throw manifestResult.error;
    assert.equal(manifestResult.status, 0, manifestResult.stderr);
    const actual = JSON.parse(manifestResult.stdout);
    const expected = JSON.parse(fs.readFileSync(path.join(repository, "packages", name, "package.json"), "utf8"));
    assert.equal(actual.name, expected.name);
    assert.equal(actual.version, expected.version);
    if (name !== "ttsc") {
      assert.deepEqual(actual.os, [process.platform]);
      assert.deepEqual(actual.cpu, [process.arch]);
    } else {
      const extraction = cp.spawnSync("tar", ["-xf", output, "-C", verification], {
        encoding: "utf8", windowsHide: true, timeout: 120_000, maxBuffer: 1024 * 1024,
      });
      if (extraction.error) throw extraction.error;
      assert.equal(extraction.status, 0, extraction.stderr);
      const current = sdkGoSources(path.join(repository, "packages", "ttsc"));
      const packed = sdkGoSources(path.join(verification, "package"));
      assert(current.length > 0, "The current SDK source receipt cannot be empty");
      assert.deepEqual(packed, current, "Borrowed SDK Go sources must match current maintained source inputs");
    }
    console.log(`Borrowed ${actual.name}@${actual.version}: sha256 ${receipt}`);
  }
  fs.rmSync(verification, { recursive: true });
}

function sdkGoSources(sdk) {
  const entries = [];
  const capture = (relative) => {
    const file = path.join(sdk, relative);
    assert(fs.lstatSync(file).isFile(), `SDK receipt input must be an ordinary file: ${file}`);
    entries.push([relative.split(path.sep).join("/"), fileDigest(file)]);
  };
  const walk = (relative) => {
    for (const entry of fs.readdirSync(path.join(sdk, relative), { withFileTypes: true })) {
      const file = path.join(relative, entry.name);
      if (entry.isDirectory()) walk(file);
      else if ((entry.name.endsWith(".go") && !entry.name.endsWith("_test.go")) || entry.name === "go.mod" || entry.name === "go.sum") capture(file);
    }
  };
  capture("go.mod");
  capture("go.sum");
  for (const directory of ["cmd", "driver", "internal", "shim", "tools", "utility"]) walk(directory);
  return entries.sort(([left], [right]) => left.localeCompare(right));
}

function fileDigest(file) {
  const descriptor = fs.openSync(file, "r");
  try {
    const digest = crypto.createHash("sha256");
    const buffer = Buffer.allocUnsafe(64 * 1024);
    for (;;) {
      const length = fs.readSync(descriptor, buffer, 0, buffer.length, null);
      if (length === 0) return digest.digest("hex");
      digest.update(buffer.subarray(0, length));
    }
  } finally {
    fs.closeSync(descriptor);
  }
}

function runInstalledBinary(binary, args) {
  const result = cp.spawnSync(binary, args, {
    cwd: workspace,
    encoding: "utf8",
    windowsHide: true,
    timeout: 120_000,
  });
  if (result.error) throw result.error;
  assert.equal(result.status, 0, result.stderr || result.stdout);
  return result.stdout;
}

function runPnpm(args, cwd) {
  const entry = process.env.npm_execpath;
  const command = entry ? process.execPath : process.platform === "win32" ? "pnpm.cmd" : "pnpm";
  const result = cp.spawnSync(command, entry ? [entry, ...args] : args, {
    cwd, stdio: "inherit", windowsHide: true,
    shell: !entry && process.platform === "win32",
  });
  if (result.error) throw result.error;
  assert.equal(result.status, 0, `pnpm ${args[0]} failed`);
}

}

module.exports = { test_installed_cli_smoke };
if (require.main === module) test_installed_cli_smoke();
