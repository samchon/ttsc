package graph

import (
  "path/filepath"
  "testing"

  "github.com/samchon/ttsc/packages/ttsc/driver"
)

// nodeModulesGlobalFixtureTSConfig compiles a project whose ambient global is
// declared by a dependency's raw `.ts` source. Both inputs are named because
// the declaring file is reached by neither an import nor a glob, and no
// `rootDir` or `outDir` is set because a `node_modules` input under one would
// be an input outside the root.
const nodeModulesGlobalFixtureTSConfig = `{
  "compilerOptions": {
    "target": "ES2022",
    "module": "commonjs",
    "strict": true
  },
  "files": ["node_modules/dep/globals.ts", "src/main.ts"]
}
`

// TestAssignedImplementationsOfNodeModulesSymbolsLeaveNoEdgeSource verifies the
// other half of the external boundary: a symbol declared under `node_modules`
// gains no outgoing edge from an assignment either.
//
// `IsWorkspaceSourceFile` refuses a file for two disjoint reasons, and only one
// of them is being a declaration file. A dependency that ships raw TypeScript
// is not a declaration file and still owns no outgoing source facts, so an
// assignment to something it declares must be refused by the same rule. Without
// this case the fix is pinned on one branch of the classifier and a change to
// the other would pass.
//
//  1. Compile a fixture whose `node_modules/dep/globals.ts` declares `var
//     patched` in a global augmentation and whose `src/main.ts` assigns an arrow
//     function to it that calls a local `helper`.
//  2. Build the graph.
//  3. Assert no edge leaves an external node, and that `main.ts`'s module node
//     still owns the value-call edge to `helper`.
//
// @evidence contracts/testing.md#behavioral-verification driver.LoadProgram loads a project whose files list names node_modules/dep/globals.ts, a raw .ts declaring `var patched` in a global augmentation, and src/main.ts, which assigns an arrow function to patched that calls a local helper; Build then yields no edge whose source node is External and an EdgeValueCall edge from main.ts's module node to the helper node. Re-attributing the assigned body to the external symbol would add an edge from an external node and fail the first loop, and losing the call altogether would fail the final edge assertion.
// @evidence contracts/testing.md#independent-expectations The expected ownership comes from the boundary stated by IsWorkspaceSourceFile and assignedFunctionTarget (an external node owns no outgoing edge, so the running module owns the assigned body's calls) applied to the literal fixture sources. The module and helper ids are built with the package's own moduleID and nodeID, so a change to the id grammar would not be caught by this test.
// @evidence contracts/testing.md#distinguishing-cases The declaring file is a non-declaration .ts under node_modules, so only the path-segment branch of IsWorkspaceSourceFile refuses it; the declaration-file branch is covered by the sibling declaration-file test. The test pairs the absent external-source edge with the present module-owned edge so a graph with no edges at all cannot pass. It has one fixture and no case where the assignment target is a workspace symbol.
// @evidence contracts/testing.md#execution-ownership This graph Go source-unit writes its fixture under t.TempDir, constructs and closes a driver compiler Program in-process, and calls Build. A restored empty linked-plugin manifest excludes ambient hooks; it installs no consumer and builds or starts no native product command.
func TestAssignedImplementationsOfNodeModulesSymbolsLeaveNoEdgeSource(t *testing.T) {
  t.Setenv(driver.LinkedPluginsEnv, "")
  root := t.TempDir()
  writeFile(t, filepath.Join(root, "tsconfig.json"), nodeModulesGlobalFixtureTSConfig)
  writeFile(t, filepath.Join(root, "node_modules", "dep", "package.json"), `{
  "name": "dep",
  "version": "1.0.0"
}
`)
  writeFile(t, filepath.Join(root, "node_modules", "dep", "globals.ts"), `declare global {
  var patched: (message: string) => void;
}
export {};
`)
  writeFile(t, filepath.Join(root, "src", "main.ts"), `export function helper(): void {}
patched = (message: string): void => {
  helper();
};
`)

  prog, diags, err := driver.LoadProgram(root, "tsconfig.json", driver.LoadProgramOptions{})
  if err != nil {
    t.Fatal(err)
  }
  if len(diags) != 0 {
    t.Fatalf("unexpected diagnostics: %v", diags)
  }
  defer func() { _ = prog.Close() }()

  graph := Build(prog)
  mainPath := sourceFile(t, prog, "main.ts").FileName()

  for _, edge := range graph.Edges {
    node, ok := graph.Nodes[edge.From]
    if ok && node.External {
      t.Fatalf("edge leaves the external boundary: %s -> %s (%s), source declared in %s", edge.From, edge.To, edge.Kind, node.File)
    }
  }

  module := moduleID(mainPath.AsString())
  helper := nodeID(mainPath.AsString(), "helper", NodeFunction)
  if !hasEdge(graph, module, helper, EdgeValueCall) {
    t.Fatalf("the assigned body's call to helper is not owned by the running module; edges: %v", graph.Edges)
  }
}
