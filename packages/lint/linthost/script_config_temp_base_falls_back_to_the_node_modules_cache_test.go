package linthost

import (
  "os"
  "path/filepath"
  "testing"
)

// TestScriptConfigTempBaseFallsBackToTheNodeModulesCache verifies that a script
// lint config keeps a private result parent when no system temporary directory
// qualifies.
//
// A project marker above the system temporary directory, such as a
// package.json in the account's home directory, refused every script config.
// The fixture marks the ambient and Windows profile temporary directories, and
// a resolution root at the volume root contains the POSIX platform directory.
//
// 1. Select a clean system temporary directory for an ordinary config.
// 2. Disqualify every system directory and select the config's node_modules/.cache.
// 3. Remove the installation and observe the empty refusal.
//
// @evidence contracts/testing.md#behavioral-verification Calls scriptConfigTempBase with authored temporary, profile and installation directories and asserts the selected parent or the refusal.
// @evidence contracts/testing.md#independent-expectations The clean directory, the physical node_modules/.cache beside the config and the empty refusal follow the private scratch placement contract, not the selector's output.
// @evidence contracts/testing.md#distinguishing-cases A clean temporary directory keeps the system parent. Marked ambient and profile directories with a volume-root resolution fall back to the installation cache, and the same input without an installation refuses.
// @evidence contracts/testing.md#execution-ownership This Go unit calls the selector in-process. It redirects only the profile variable through t.Setenv and launches no host or Node process.
func TestScriptConfigTempBaseFallsBackToTheNodeModulesCache(t *testing.T) {
  root, err := filepath.EvalSymlinks(t.TempDir())
  if err != nil {
    t.Fatal(err)
  }
  project := filepath.Join(root, "project")
  modules := filepath.Join(project, "node_modules")
  clean := filepath.Join(root, "clean")
  home := filepath.Join(root, "home")
  ambient := filepath.Join(home, "temp")
  for _, directory := range []string{
    modules,
    clean,
    ambient,
    filepath.Join(home, "AppData", "Local", "Temp"),
  } {
    if err := os.MkdirAll(directory, 0o755); err != nil {
      t.Fatal(err)
    }
  }
  if err := os.WriteFile(filepath.Join(home, "package.json"), []byte("{}\n"), 0o644); err != nil {
    t.Fatal(err)
  }
  config := filepath.Join(project, "lint.config.cjs")
  if err := os.WriteFile(config, []byte("module.exports = {};\n"), 0o644); err != nil {
    t.Fatal(err)
  }
  t.Setenv("USERPROFILE", home)

  if base := scriptConfigTempBase(config, project, clean); base != clean {
    t.Fatalf("clean temporary base = %q, want %q", base, clean)
  }
  volume := filepath.VolumeName(root) + string(filepath.Separator)
  want := filepath.Join(modules, ".cache")
  if base := scriptConfigTempBase(config, volume, ambient); base != want {
    t.Fatalf("fallback base = %q, want %q", base, want)
  }
  if err := os.RemoveAll(modules); err != nil {
    t.Fatal(err)
  }
  if base := scriptConfigTempBase(config, volume, ambient); base != "" {
    t.Fatalf("base without an installation = %q, want refusal", base)
  }
}
