package linthost

import (
  "path/filepath"
  "testing"
)

// TestNodePackageManifestFromSkipsANodeModulesDirectory verifies the upward walk
// never proposes `node_modules/node_modules`.
//
// Node's Module._nodeModulePaths contributes no candidate for a directory that
// is already named `node_modules`, so a dependency of an installed package
// resolves to its sibling in the same node_modules rather than through a nested
// one. The compiler resolution rides on exactly that step: the platform package
// is a sibling of `typescript`, one level up from it. A decoy makes the skip
// observable: without the decoy, a wrong extra candidate could miss and the
// same sibling could still be selected.
//
//  1. Install a package and a sibling under one node_modules.
//  2. Plant a decoy under `node_modules/node_modules`.
//  3. Assert the sibling wins, and that an absent package resolves to nothing.
//
// @evidence contracts/testing.md#behavioral-verification nodePackageManifestFrom selects the sibling manifest over a decoy nested node_modules/node_modules manifest and returns empty for an absent package.
// @evidence contracts/testing.md#independent-expectations Node module-path ancestry skips a directory already named node_modules; independently planted sibling and decoy files distinguish that specified search order.
// @evidence contracts/testing.md#distinguishing-cases Owns the installed-host anchor, a misleading nested candidate, and a missing scoped package; relative-anchor absolutization is checked separately.
// @evidence contracts/testing.md#execution-ownership This discoverable Go entry owns the case described above. Authored sibling and nested-decoy manifests reach nodePackageManifestFrom directly in-process; selected path and absent-package miss observe search order without executing Node or a native host.
func TestNodePackageManifestFromSkipsANodeModulesDirectory(t *testing.T) {
  root := realpathIfPossible(t.TempDir())
  modules := filepath.Join(root, "node_modules")
  anchor := filepath.Join(modules, "host", "package.json")
  writeFile(t, anchor, `{"name":"host"}`)
  want := filepath.Join(modules, "sibling", "package.json")
  writeFile(t, want, `{"name":"sibling"}`)
  decoy := filepath.Join(modules, "node_modules", "sibling", "package.json")
  writeFile(t, decoy, `{"name":"decoy"}`)

  got := nodePackageManifestFrom(anchor, "sibling")
  if got == decoy {
    t.Fatalf("nodePackageManifestFrom resolved through node_modules/node_modules: %q", got)
  }
  if got != want {
    t.Fatalf("nodePackageManifestFrom = %q, want the sibling install %q", got, want)
  }
  // The negative twin: a package that exists nowhere on the walk stays
  // unresolved rather than being reported at a synthesized location. The name
  // is scoped and fictional to reduce accidental ambient matches; it does not
  // isolate ancestors outside the authored temp fixture.
  if got := nodePackageManifestFrom(anchor, "@ttsc/fixture-package-that-is-never-installed"); got != "" {
    t.Fatalf("nodePackageManifestFrom resolved an absent package to %q", got)
  }
}
