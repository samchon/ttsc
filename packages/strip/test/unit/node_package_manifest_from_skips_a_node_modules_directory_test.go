package strip_test

import (
  "path/filepath"
  "testing"

  shared "github.com/samchon/ttsc/packages/strip/test/internal/shared"
)

// TestNodePackageManifestFromSkipsANodeModulesDirectory verifies the upward walk
// never proposes `node_modules/node_modules`.
//
// Node's Module._nodeModulePaths contributes no candidate for a directory that
// is already named `node_modules`, so a dependency of an installed package
// resolves to its sibling in the same node_modules rather than through a nested
// one. The compiler resolution rides on exactly that step: the platform package
// is a sibling of `typescript`, one level up from it. A decoy makes the skip
// observable, because without it the two candidates would both miss.
//
//  1. Install a package and a sibling under one node_modules.
//  2. Plant a decoy under `node_modules/node_modules`.
//  3. Assert the sibling wins, and that absent or blank inputs resolve to
//     nothing.
//
// @evidence contracts/testing.md#behavioral-verification Calls stripNodePackageManifestFrom for a host inside node_modules and asserts the sibling manifest wins over the node_modules/node_modules decoy; absent and blank inputs return empty.
// @evidence contracts/testing.md#independent-expectations Node search paths omit an extra node_modules hop when an ancestor already has that name. Distinct literal sibling and decoy paths expose an incorrect walk.
// @evidence contracts/testing.md#distinguishing-cases Owns sibling/decoy precedence, absent scoped package, blank anchor and blank package; relative-anchor normalization has a separate owner.
// @evidence contracts/testing.md#execution-ownership Unit entry TestNodePackageManifestFromSkipsANodeModulesDirectory is discovered in test/unit by `go test ./packages/strip/...`, the root `test:go` command. Runs stripNodePackageManifestFrom through linkname in the Go test process with ordinary manifest fixtures and no Node invocation.
func TestNodePackageManifestFromSkipsANodeModulesDirectory(t *testing.T) {
  root := shared.StripRealpathIfPossible(t.TempDir())
  modules := filepath.Join(root, "node_modules")
  anchor := filepath.Join(modules, "host", "package.json")
  shared.WriteFile(t, anchor, `{"name":"host"}`)
  want := filepath.Join(modules, "sibling", "package.json")
  shared.WriteFile(t, want, `{"name":"sibling"}`)
  decoy := filepath.Join(modules, "node_modules", "sibling", "package.json")
  shared.WriteFile(t, decoy, `{"name":"decoy"}`)

  got := stripNodePackageManifestFrom(anchor, "sibling")
  if got == decoy {
    t.Fatalf("stripNodePackageManifestFrom resolved through node_modules/node_modules: %q", got)
  }
  if got != want {
    t.Fatalf("stripNodePackageManifestFrom = %q, want the sibling install %q", got, want)
  }
  // The negative twins: a package that exists nowhere on the walk stays
  // unresolved rather than being reported at a synthesized location, and a
  // blank anchor or package name resolves nothing at all rather than walking
  // up from the process working directory. The absent name is scoped and
  // fictional so no ambient install above the temp dir can answer for it.
  if got := stripNodePackageManifestFrom(anchor, "@ttsc/fixture-package-that-is-never-installed"); got != "" {
    t.Fatalf("stripNodePackageManifestFrom resolved an absent package to %q", got)
  }
  if got := stripNodePackageManifestFrom("   ", "sibling"); got != "" {
    t.Fatalf("stripNodePackageManifestFrom resolved from a blank anchor to %q", got)
  }
  if got := stripNodePackageManifestFrom(anchor, ""); got != "" {
    t.Fatalf("stripNodePackageManifestFrom resolved a blank package name to %q", got)
  }
}
